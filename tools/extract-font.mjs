// Converts Monument Extended to outline data so the tool can set any text
// without a font file at run time.  Run: node tools/extract-font.mjs
// Needs the fonts installed in ~/Library/Fonts (or pass a folder as argument).
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';

const dir = process.argv[2] || `${homedir()}/Library/Fonts`;
const FILES = { regular: 'MonumentExtended-Regular.otf', ultrabold: 'MonumentExtended-Ultrabold.otf' };
// Basic Latin, Latin-1, and the punctuation a designer reaches for.
let chars = '';
for (let c = 32; c < 127; c++) chars += String.fromCharCode(c);
for (let c = 161; c < 256; c++) chars += String.fromCharCode(c);
chars += '–—‘’“”•…™€←↑→↓×';

const out = {};
for (const [key, file] of Object.entries(FILES)) {
  const buf = readFileSync(`${dir}/${file}`);
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const em = font.unitsPerEm;
  const glyphs = {}, have = [];
  for (const ch of chars) {
    const g = font.charToGlyph(ch);
    if (!g || g.index === 0) continue;
    glyphs[ch] = { a: Math.round(g.advanceWidth), d: g.getPath(0, 0, em).toPathData(0) };
    have.push([ch, g]);
  }
  const kern = {};
  for (const [a, ga] of have) for (const [b, gb] of have) {
    const k = font.getKerningValue(ga, gb);
    if (k) kern[a + b] = Math.round(k);
  }
  const box = (ch) => font.charToGlyph(ch).getBoundingBox();
  out[key] = {
    em, xHeight: Math.round(-0 + box('x').y2), capHeight: Math.round(box('H').y2),
    ascender: font.ascender, descender: font.descender, glyphs, kern,
  };
  console.log(key, Object.keys(glyphs).length, 'glyphs', Object.keys(kern).length, 'kerning pairs', 'x-height', out[key].xHeight);
}
writeFileSync('src/font-data.js', '// Monument Extended as outlines (font units, y down, baseline at 0). Generated by tools/extract-font.mjs.\nexport const FONTS = ' + JSON.stringify(out) + ';\n');
